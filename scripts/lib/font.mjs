// glifo = { rows: string[], top: number } — top é a linha (em pixels) onde começa
const GLYPHS = {};
for (const [ch, s] of Object.entries(RAW)) GLYPHS[ch] = { rows: s.split('|'), top: 0 };
for (const [ch, [base, acc]] of Object.entries(ACCENTED)) {
  const b = GLYPHS[base].rows;
  if (base === base.toUpperCase()) {
    GLYPHS[ch] = { rows: [...ACCENT[acc], ...b], top: -2 };
  } else {
    // minúsculas: o acento ocupa as linhas 0-1 (área acima da altura-x)
    const body = base === 'i' ? ['.....', '.....', '.##..', '..#..', '..#..', '..#..', '.###.'] : b;
    GLYPHS[ch] = { rows: [...ACCENT[acc], ...body.slice(2)], top: 0 };
  }
}
GLYPHS['Ç'] = { rows: [...GLYPHS.C.rows, '..#..', '.##..'], top: 0 };
GLYPHS['ç'] = { rows: [...GLYPHS.c.rows, '..#..', '.##..'], top: 0 };

export const ADV = 6; // avanço por caractere (5 px + 1 de espaço)
export const CAP = 7; // altura das maiúsculas

const missing = new Set();

/** Largura do texto em unidades de pixel (antes da escala). */
export function measure(str) {
  const n = Array.from(str).length;
  return n ? n * ADV - 1 : 0;
}

/** d de um <path> com o texto em coordenadas de grade (1 unidade = 1 pixel da fonte). */
export function textD(str, ox = 0, oy = 0) {
  let d = '';
  let x = ox;
  for (const ch of Array.from(str)) {
    let g = GLYPHS[ch];
    if (!g) {
      const up = ch.toUpperCase();
      g = GLYPHS[up];
      if (!g) {
        missing.add(ch);
        g = GLYPHS['?'];
      }
    }
    g.rows.forEach((row, r) => {
      const y = oy + g.top + r;
      let c = 0;
      while (c < row.length) {
        if (row[c] === '#') {
          let e = c;
          while (e < row.length && row[e] === '#') e++;
          d += `M${x + c} ${y}h${e - c}v1h-${e - c}z`;
          c = e;
        } else c++;
      }
    });
    x += ADV;
  }
  return d;
}

/**
 * Texto pixelado posicionado. (x, y) = canto superior esquerdo da caixa de maiúsculas.
 * opts: { s: escala, fill, anchor: 'start'|'middle'|'end', attrs: string }
 */
export function px(str, x, y, opts = {}) {
  const { s = 2, fill = '#fff', anchor = 'start', attrs = '' } = opts;
  const w = measure(str) * s;
  const tx = anchor === 'middle' ? x - w / 2 : anchor === 'end' ? x - w : x;
  const path = `<path transform="translate(${r2(tx)} ${r2(y)}) scale(${s})" fill="${fill}" d="${textD(str)}"/>`;
  // atributos (filter, class...) vão num <g> para o filtro não ser escalado junto com o texto
  return attrs ? `<g ${attrs}>${path}</g>` : path;
}

/** Largura renderizada (px) */
export function pxWidth(str, s = 2) {
  return measure(str) * s;
}

/** Sprite a partir de linhas ('#' = pixel aceso) */
export function spriteD(rows, ox = 0, oy = 0) {
  let d = '';
  rows.forEach((row, r) => {
    let c = 0;
    while (c < row.length) {
      if (row[c] === '#') {
        let e = c;
        while (e < row.length && row[e] === '#') e++;
        d += `M${ox + c} ${oy + r}h${e - c}v1h-${e - c}z`;
        c = e;
      } else c++;
    }
  });
  return d;
}

export function reportMissing() {
  if (missing.size) console.warn('[font] glifos ausentes:', [...missing].join(' '));
}

const r2 = (n) => Math.round(n * 100) / 100;
